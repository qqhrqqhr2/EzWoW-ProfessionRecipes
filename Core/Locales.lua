function LocaleRegistry.commitLanguage()
    local langCode = ns.DB and ns.DB.lang or "auto"
    if LOCALE_TABLES[langCode] then
        ns.ACTIVE_LANG = langCode
    else
        ns.ACTIVE_LANG = CLIENT_LANG
    end
    ns.IS_KO = (ns.ACTIVE_LANG == "ko")
    ns.LI = ns.IS_KO and 1 or 2
    ns.L_ACTIVE = LOCALE_TABLES[ns.ACTIVE_LANG] or L_EN
end

function LocaleRegistry.bootstrapDB()
    if type(EzWoW_ProfessionRecipesDB) ~= "table" then
        if type(EzWoW_ProfessionRecipesDB) == "table" then
            EzWoW_ProfessionRecipesDB = EzWoW_ProfessionRecipesDB
        else
            EzWoW_ProfessionRecipesDB = {}
        end
    end
    EzWoW_ProfessionRecipesDB = EzWoW_ProfessionRecipesDB
    ns.DB = EzWoW_ProfessionRecipesDB
    for entryKey, entryValue in pairs(DEFAULTS) do
        if ns.DB[entryKey] == nil then ns.DB[entryKey] = (type(entryValue) == "table") and {} or entryValue end
    end
    LocaleRegistry.commitLanguage()
    if ns.UpdateQuickModifier then ns.UpdateQuickModifier() end
end

